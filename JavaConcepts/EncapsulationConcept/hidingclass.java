package EncapsulationConcept;

public class hidingclass {
	private int salary;
	private String name;
	public int getSalary() {
		
		return salary;
		
		
	}
//setter method
	
	public void setSalary(String name,int salary) {
		this.name=name;
		this.salary=salary;
		
	}
	//getter method
	public String getName() {
		return name;
		
		
	}

}
